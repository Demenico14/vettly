/** Theta-scored adaptive tests: theta is ~N(0,1) in the calibration sample; each norm shifts it. */
const thetaNorm = (testId: string, normCode: string, n: number, mean: number, sd = 1): NormTable => ({ testId, normCode, n, mean, sd });
const rawNorm = thetaNorm;

/** Scale-level norms for Likert questionnaires: mean and SD of the scale sum, with small group differences. */
function scaleNorms(testId: string, normCode: string, n: number, shift = 0): NormTable[] {
  const t = tests.find((x) => x.id === testId)!;
  const points = t.itemFormat === "likert_7" ? 7 : 5;
  return t.scales.map((sc, i) => {
    const k = sc.itemCount;
    const mid = ((points + 1) / 2 + (points === 7 ? 0.6 : 0.4)) * k;
    const wobble = (((i * 37) % 11) - 5) / 10;
    return { testId, normCode, n, scale: sc.code, mean: Math.round((mid + wobble + shift * k * 0.05) * 10) / 10, sd: Math.round(0.62 * k * (points === 7 ? 1.25 : 1) * 10) / 10 };
  });
}

/** Forced-choice IRT scales: theta per scale. */
function thetaScaleNorms(testId: string, normCode: string, n: number, shift = 0): NormTable[] {
  const t = tests.find((x) => x.id === testId)!;
  return t.scales.map((sc, i) => ({ testId, normCode, n, scale: sc.code, mean: Math.round(((((i * 13) % 7) - 3) / 20 + shift) * 100) / 100, sd: 1 }));
}

